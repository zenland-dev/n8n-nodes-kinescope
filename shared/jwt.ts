import {
	createHash,
	createPrivateKey,
	createPublicKey,
	createSign,
	type KeyObject,
} from 'node:crypto';
import type { IDataObject, IExecuteFunctions } from 'n8n-workflow';
import { NodeOperationError } from 'n8n-workflow';

import { CREDENTIAL, kinescopeRequest, readPages, workspaceKey } from './transport';

/**
 * A PEM block put back into shape. A key pasted into a single-line field
 * reaches the node with its line breaks turned into spaces, or as literal \n.
 */
export function normalizePem(raw: string): string {
	const text = raw.replace(/\\n/g, '\n').trim();
	const match = /-----BEGIN ([A-Z ]+)-----([\s\S]*?)-----END \1-----/.exec(text);
	if (match === null) return text;
	const body = match[2].replace(/\s+/g, '');
	const lines = body.match(/.{1,64}/g) ?? [];
	return `-----BEGIN ${match[1]}-----\n${lines.join('\n')}\n-----END ${match[1]}-----\n`;
}

/** The public half of the key in the JWK form Kinescope stores. */
export function publicJwk(key: KeyObject, kid: string): IDataObject {
	const jwk = createPublicKey(key).export({ format: 'jwk' });
	return { kty: 'RSA', e: jwk.e, n: jwk.n, use: 'sig', alg: 'RS256', kid };
}

/**
 * The ID of a generated key: a fingerprint of its public half. Two keys never
 * share it, and copies of one credential — a duplicate, an import on another
 * n8n — share the key and therefore the ID.
 */
export function generatedKeyId(key: KeyObject): string {
	const n = String(createPublicKey(key).export({ format: 'jwk' }).n);
	return `n8n-${createHash('sha256').update(n).digest('hex').slice(0, 16)}`;
}

/** The signing key of the credential and its ID, or an error saying what is missing. */
export async function signingKey(
	this: IExecuteFunctions,
	itemIndex: number,
): Promise<{ key: KeyObject; kid: string }> {
	const credentials = await this.getCredentials(CREDENTIAL);
	const own = credentials.signingKeySource === 'own';
	const pem = String(
		(own ? credentials.signingPrivateKey : credentials.generatedPrivateKey) ?? '',
	).trim();
	const ownKid = String(credentials.signingKeyId ?? '').trim();

	if (own && (pem === '' || ownKid === '')) {
		throw new NodeOperationError(this.getNode(), 'The credential has no signing key', {
			itemIndex,
			description:
				'Admin Link Signing Key is set to My Own Key: fill in Signing Private Key and Signing Key ID, or switch it to Generated by n8n.',
		});
	}

	if (pem === '') {
		throw new NodeOperationError(this.getNode(), 'n8n has not stored a generated signing key', {
			itemIndex,
			description:
				'n8n makes the key on the first request with this credential and keeps it there. If this persists, set Admin Link Signing Key to My Own Key and paste a key.',
		});
	}

	let key: KeyObject;
	try {
		key = createPrivateKey(normalizePem(pem));
	} catch {
		throw new NodeOperationError(this.getNode(), 'The signing private key cannot be read', {
			itemIndex,
			description:
				'Paste an RSA private key in PEM form, with its BEGIN and END lines, e.g. one made by: openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048',
		});
	}

	if (key.asymmetricKeyType !== 'rsa') {
		throw new NodeOperationError(this.getNode(), 'The signing key must be an RSA key', {
			itemIndex,
			description: 'Kinescope verifies tokens with RS256 only.',
		});
	}

	return { key, kid: own ? ownKid : generatedKeyId(key) };
}

/** How long a key registered on first use stays valid. Kinescope requires a date and takes a far one. */
const FIRST_USE_VALIDITY_YEARS = 100;

/** Keys known to be registered, per token, so a run of links reads the list once. */
const registered = new Set<string>();

/**
 * Makes sure Kinescope holds the public half of the key under its ID,
 * registering it on first use. A different key already registered under the
 * same ID, or an expired one, is an error: links would not verify.
 */
export async function ensureRegistered(
	this: IExecuteFunctions,
	key: KeyObject,
	kid: string,
	itemIndex: number,
): Promise<void> {
	const jwk = publicJwk(key, kid);
	const memo = `${await workspaceKey.call(this)}:${kid}:${String(jwk.n).slice(0, 32)}`;
	if (registered.has(memo)) return;

	const existing = (await readPages.call(this, '/v1/jwk', {}, undefined, itemIndex)).find(
		(entry) => String(entry.kid) === kid,
	);

	if (existing !== undefined) {
		if (String(existing.n) !== String(jwk.n)) {
			throw new NodeOperationError(this.getNode(), `Another key is registered as ${kid}`, {
				itemIndex,
				description:
					'Kinescope holds a different public key under this Signing Key ID, so links signed here would not verify. Give the credential another Signing Key ID, or delete the old key with Signing Key → Delete.',
			});
		}
		if (Date.parse(String(existing.expires_at ?? '')) <= Date.now()) {
			throw new NodeOperationError(
				this.getNode(),
				`The signing key ${kid} has expired in Kinescope`,
				{
					itemIndex,
					description:
						'Delete it with Signing Key → Delete; the next admin link registers the key again. For your own key, Signing Key → Register sets a new expiry.',
				},
			);
		}
	} else {
		const expires = new Date();
		expires.setUTCFullYear(expires.getUTCFullYear() + FIRST_USE_VALIDITY_YEARS);
		await kinescopeRequest.call(this, 'POST', '/v1/jwk', {
			body: { ...jwk, expires_at: expires.toISOString().replace(/\.\d+Z$/, 'Z') },
			itemIndex,
			retry: false,
		});
	}

	registered.add(memo);
}

function base64url(value: unknown): string {
	return Buffer.from(JSON.stringify(value)).toString('base64url');
}

/** An RS256 JSON Web Token, with the key ID in its header. */
export function signJwt(key: KeyObject, kid: string, claims: IDataObject): string {
	const head = base64url({ alg: 'RS256', typ: 'JWT', kid });
	const body = base64url(claims);
	const signature = createSign('RSA-SHA256')
		.update(`${head}.${body}`)
		.sign(key)
		.toString('base64url');
	return `${head}.${body}.${signature}`;
}
